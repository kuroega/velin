#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Builds build/ios/MPVKit, a local Swift package with MPVKit's GPL libmpv,
# FFmpeg and dependency xcframeworks, from zips you downloaded yourself.
# Every zip must match the SHA-256 pinned in config/mpvkit-ios.txt, whose
# third column lists the download URLs. Nothing is downloaded here.
#
# Usage: scripts/prepare-mpvkit.sh <folder with the .xcframework.zip files>
set -euo pipefail

if [[ $# -ne 1 || ! -d "$1" ]]; then
    echo "Usage: $0 <folder with the MPVKit .xcframework.zip files>" >&2
    exit 2
fi
source_dir="$(cd "$1" && pwd)"
root="$(cd "$(dirname "$0")/.." && pwd)"
package="$root/build/ios/MPVKit"
staging="$package.staging"
rm -rf "$staging"
mkdir -p "$staging/Frameworks" "$staging/Sources/_MPVKit-GPL" "$staging/Sources/_FFmpeg-GPL"

targets=()
while read -r name checksum url; do
    [[ -z "$name" || "$name" == \#* ]] && continue
    zip="$source_dir/${url##*/}"
    if [[ ! -f "$zip" ]]; then echo "Missing ${url##*/} (download $url)" >&2; exit 1; fi
    actual="$(shasum -a 256 "$zip" | cut -d' ' -f1)"
    if [[ "$actual" != "$checksum" ]]; then echo "Checksum mismatch for ${url##*/}" >&2; exit 1; fi
    unzip -q "$zip" -d "$staging/Frameworks/$name.unzip"
    framework="$(find "$staging/Frameworks/$name.unzip" -maxdepth 2 -name '*.xcframework' -type d | head -n 1)"
    if [[ -z "$framework" ]]; then echo "No xcframework in ${url##*/}" >&2; exit 1; fi
    mv "$framework" "$staging/Frameworks/$name.xcframework"
    rm -rf "$staging/Frameworks/$name.unzip"
    targets+=("$name")
done < "$root/config/mpvkit-ios.txt"
echo "Verified ${#targets[@]} MPVKit binaries"

# MPVKit's shaderc (glslang) objects define their own global copies of the
# C++ runtime's type info (std::exception, std::bad_alloc, std::logic_error,
# ...). Linked into the app, Velin's `catch (const std::exception&)` binds to
# those copies while thrown exceptions use libc++abi's, so no handler ever
# matches and the app terminates. Make the copies local to shaderc.
localize_runtime_typeinfo() {
    local library="$1" symbols work arch
    work="$(mktemp -d)"
    symbols="$work/symbols.txt"
    for arch in $(lipo -archs "$library"); do
        lipo "$library" -thin "$arch" -output "$work/$arch.a"
        nm -g --defined-only "$work/$arch.a" 2>/dev/null | awk '{print $3}' |
            grep -E '^__ZT[ISV](St[0-9]+[A-Za-z_]+|NSt3__1[0-9]+[A-Za-z_]+E)$' | sort -u > "$symbols" || true
        if [[ -s "$symbols" ]]; then
            xcrun nmedit -R "$symbols" "$work/$arch.a" -o "$work/$arch.edited.a"
            mv "$work/$arch.edited.a" "$work/$arch.a"
        fi
    done
    lipo -create "$work"/*.a -output "$library"
    rm -rf "$work"
}
for slice in "$staging"/Frameworks/Libshaderc_combined.xcframework/ios-*; do
    [[ "$slice" == *maccatalyst* ]] && continue
    localize_runtime_typeinfo "$slice/Libshaderc_combined.framework/Libshaderc_combined"
done
echo "Localized shaderc's copies of the C++ runtime type info"

# SwiftPM needs a source file in each wrapper target.
echo "// Links libmpv and its libraries; no code." > "$staging/Sources/_MPVKit-GPL/MPVKit.swift"
echo "// Links FFmpeg and its libraries; no code." > "$staging/Sources/_FFmpeg-GPL/FFmpeg.swift"

binary_targets=""
for name in "${targets[@]}"; do
    binary_targets+="        .binaryTarget(name: \"$name\", path: \"Frameworks/$name.xcframework\"),"$'\n'
done

# Mirrors MPVKit's own MPVKit-GPL product (iOS only).
cat > "$staging/Package.swift" <<PACKAGE
// swift-tools-version:5.9
// Generated by scripts/prepare-mpvkit.sh from MPVKit 1.1.0-n9.0.2.
import PackageDescription

let package = Package(
    name: "MPVKit",
    platforms: [.iOS(.v15)],
    products: [
        .library(name: "MPVKit-GPL", targets: ["_MPVKit-GPL"]),
    ],
    targets: [
        .target(
            name: "_MPVKit-GPL",
            dependencies: ["Libmpv-GPL", "_FFmpeg-GPL", "Libuchardet", "Libbluray"],
            path: "Sources/_MPVKit-GPL",
            linkerSettings: [.linkedFramework("AVFoundation"), .linkedFramework("CoreAudio")]
        ),
        .target(
            name: "_FFmpeg-GPL",
            dependencies: [
                "Libavcodec-GPL", "Libavdevice-GPL", "Libavfilter-GPL", "Libavformat-GPL", "Libavutil-GPL",
                "Libswresample-GPL", "Libswscale-GPL",
                "Libssl", "Libcrypto", "Libass", "Libfreetype", "Libfribidi", "Libharfbuzz",
                "MoltenVK", "Libshaderc_combined", "lcms2", "Libplacebo", "Libdovi", "Libunibreak",
                "Libsmbclient", "gmp", "nettle", "hogweed", "gnutls", "Libdav1d", "Libuavs3d",
            ],
            path: "Sources/_FFmpeg-GPL",
            linkerSettings: [
                .linkedFramework("AudioToolbox"), .linkedFramework("CoreVideo"), .linkedFramework("CoreFoundation"),
                .linkedFramework("CoreMedia"), .linkedFramework("Metal"), .linkedFramework("VideoToolbox"),
                .linkedLibrary("bz2"), .linkedLibrary("iconv"), .linkedLibrary("expat"), .linkedLibrary("resolv"),
                .linkedLibrary("xml2"), .linkedLibrary("z"), .linkedLibrary("c++"),
            ]
        ),
$binary_targets    ]
)
PACKAGE

rm -rf "$package"
mv "$staging" "$package"
echo "Prepared $package"
